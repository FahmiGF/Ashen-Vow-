// Boss voice script + recording manifest.
//
//   npm run voice:script
//
// 1. Writes docs/voice-script.md: every boss line (613 at the time of
//    writing) grouped by boss, with the voice archetype, delivery direction
//    for the actor and the exact file name each take must be saved as.
// 2. Scans assets/voice/boss/<kind>/<key>-<n>.(mp3|ogg|wav|m4a) and writes
//    assets/voice/manifest.json, which the game reads at boot. A line plays
//    as a recording only when it is listed there.

import { existsSync, mkdirSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import {
  bossVoiceScript,
  bossVoiceSummary,
  VOICE_ARCHETYPES,
  BOSS_VOICE_ROOT,
  BOSS_VOICE_SCHEMA,
} from '../src/boss_voice.js';

const rows = bossVoiceScript();
const summary = bossVoiceSummary();

// ── manifest ───────────────────────────────────────────────────────────────
const files = [];
const paths = {};
const exts = ['mp3', 'ogg', 'wav', 'm4a'];
for (const row of rows) {
  const dir = join(BOSS_VOICE_ROOT, row.kind);
  if (!existsSync(dir)) continue;
  for (const ext of exts) {
    const name = `${row.key}-${row.index + 1}.${ext}`;
    if (existsSync(join(dir, name))) {
      files.push(row.id);
      if (ext !== 'mp3') paths[row.id] = `${BOSS_VOICE_ROOT}/${row.kind}/${name}`;
      break;
    }
  }
}
mkdirSync('assets/voice', { recursive: true });
writeFileSync('assets/voice/manifest.json', `${JSON.stringify({ version: BOSS_VOICE_SCHEMA, files, paths }, null, 2)}\n`);

// Unknown files are usually typos in a take's name; report them.
const strays = [];
if (existsSync(BOSS_VOICE_ROOT)) {
  const known = new Set(rows.map((r) => `${r.kind}/${r.key}-${r.index + 1}`));
  for (const kind of readdirSync(BOSS_VOICE_ROOT)) {
    const dir = join(BOSS_VOICE_ROOT, kind);
    for (const name of readdirSync(dir)) {
      const stem = `${kind}/${name.replace(/\.(mp3|ogg|wav|m4a)$/i, '')}`;
      if (!known.has(stem)) strays.push(`${kind}/${name}`);
    }
  }
}

// ── script ─────────────────────────────────────────────────────────────────
const byBoss = new Map();
for (const row of rows) {
  if (!byBoss.has(row.kind)) byBoss.set(row.kind, []);
  byBoss.get(row.kind).push(row);
}
const recorded = new Set(files);
const out = [];
out.push('# Ashen Vow: naskah suara boss (boss voice script)');
out.push('');
out.push('Generated by `npm run voice:script` from the dialogue tables in `src/`. Do not edit by hand.');
out.push('');
out.push(`- **${summary.lines} lines** across **${summary.bosses} bosses** (${summary.bossLines} boss lines, ${summary.playerLines} lines for the player character, The Oathbound).`);
out.push(`- **Recorded so far: ${files.length} / ${summary.lines}.** Any line without a recording plays a wordless cinematic sting under its subtitle.`);
out.push('');
out.push('## How to deliver a take');
out.push('');
out.push(`Save each take as \`${BOSS_VOICE_ROOT}/<boss-id>/<key>-<n>.mp3\` (OGG, WAV and M4A also work), mono, 44.1 or 48 kHz, peaks at about -3 dBFS, **dry**: no reverb or effects. The game adds pitch, weight, doubling and reverb per archetype, so a clean, close take sounds best. Then run \`npm run voice:script\` to refresh the manifest.`);
out.push('');
out.push('## Archetypes');
out.push('');
out.push('| Archetype | Lines | Direction |');
out.push('| --- | ---: | --- |');
for (const [id, a] of Object.entries(VOICE_ARCHETYPES)) {
  out.push(`| **${a.label}** (\`${id}\`) | ${summary.archetypes[id] || 0} | ${a.direction} |`);
}
out.push('');
out.push('## Lines by boss');
for (const [kind, list] of byBoss) {
  const bossArchetype = list.find((r) => r.archetype !== 'hero')?.archetype || 'regal';
  out.push('');
  out.push(`### ${list[0].boss} (\`${kind}\`): ${VOICE_ARCHETYPES[bossArchetype].label}`);
  out.push('');
  out.push('| File | Key | Speaker | Line | Recorded |');
  out.push('| --- | --- | --- | --- | :---: |');
  for (const r of list) {
    const text = r.text.replace(/\|/g, '\\|');
    out.push(`| \`${r.kind}/${r.key}-${r.index + 1}\` | ${r.key} | ${r.speaker} | ${text} | ${recorded.has(r.id) ? '✓' : ''} |`);
  }
}
out.push('');
writeFileSync('docs/voice-script.md', out.join('\n'));

console.log(`voice script: ${summary.lines} lines / ${summary.bosses} bosses -> docs/voice-script.md`);
console.log(`manifest: ${files.length} recorded line(s) -> assets/voice/manifest.json`);
if (strays.length) console.log(`unmatched files (check their names): ${strays.join(', ')}`);
