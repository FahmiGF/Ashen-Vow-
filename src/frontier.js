export function sanitizeFrontierProgress(raw = {}) {
  const defaults = defaultFrontierProgress();
  if (!raw || typeof raw !== 'object') return defaults;
  return {
    version: FRONTIER_VERSION,
    highestLevel: Math.max(101, Math.min(200, Number(raw.highestLevel) || 101)),
    clearedLevels: typeof raw.clearedLevels === 'object' && raw.clearedLevels ? { ...raw.clearedLevels } : {},
    unlockedClasses: Array.isArray(raw.unlockedClasses) && raw.unlockedClasses.length > 0 ? [...raw.unlockedClasses] : ['warden'],
    activeClass: FRONTIER_CLASS_BY_ID[raw.activeClass] ? raw.activeClass : 'warden',
    classSpecializations: typeof raw.classSpecializations === 'object' && raw.classSpecializations ? { ...raw.classSpecializations } : { warden: 'fortress' },
    classMastery: typeof raw.classMastery === 'object' && raw.classMastery ? { ...raw.classMastery } : { warden: 1 },
    coreAttributes: {
      ...defaults.coreAttributes,
      ...(typeof raw.coreAttributes === 'object' && raw.coreAttributes ? raw.coreAttributes : {}),
    },
    attributePoints: Math.max(0, Number(raw.attributePoints) || 0),
    discoveredElites: typeof raw.discoveredElites === 'object' && raw.discoveredElites ? { ...raw.discoveredElites } : {},
    inventoryMaterials: {
      ...defaults.inventoryMaterials,
      ...(typeof raw.inventoryMaterials === 'object' && raw.inventoryMaterials ? raw.inventoryMaterials : {}),
    },
    craftedWeapons: Array.isArray(raw.craftedWeapons) ? [...raw.craftedWeapons] : ['solvar_greatsword'],
    equippedWeapon: raw.equippedWeapon || 'solvar_greatsword',
    customization: {
      ...defaults.customization,
      ...(typeof raw.customization === 'object' && raw.customization ? raw.customization : {}),
    },
    activeMount: raw.activeMount || 'thornveil_stag',
    activeCompanion: raw.activeCompanion || 'spirit_wolf',
    companionBonds: typeof raw.companionBonds === 'object' && raw.companionBonds ? { ...raw.companionBonds } : { spirit_wolf: 1 },
    unlockedMounts: Array.isArray(raw.unlockedMounts) ? [...raw.unlockedMounts] : ['ashen_warhorse', 'thornveil_stag'],
    unlockedCompanions: Array.isArray(raw.unlockedCompanions) ? [...raw.unlockedCompanions] : ['spirit_wolf', 'ancient_wisp'],
    traversal3D: {
      ...defaults.traversal3D,
      ...(typeof raw.traversal3D === 'object' && raw.traversal3D ? raw.traversal3D : {}),
    },
    mode3DProgress: {
      ...defaults.mode3DProgress,
      ...(typeof raw.mode3DProgress === 'object' && raw.mode3DProgress ? raw.mode3DProgress : {}),
    },
    checklistPassed: Array.isArray(raw.checklistPassed) ? [...raw.checklistPassed] : defaults.checklistPassed,
  };
}

export function levelSpecByNumber(levelNumber) {
  const num = Math.max(101, Math.min(200, Number(levelNumber) || 101));
  return FRONTIER_LEVEL_SPECS[num - 101] || FRONTIER_LEVEL_SPECS[0];
}

export function chapterForLevel(levelNumber) {
  const spec = levelSpecByNumber(levelNumber);
  return FRONTIER_CHAPTERS.find((c) => c.number === spec.chapter) || FRONTIER_CHAPTERS[0];
}
